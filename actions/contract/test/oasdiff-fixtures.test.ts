import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { cachedOasdiff, ChecksumError, installOasdiff, OASDIFF } from "../src/oasdiff.ts";
import { OASDIFF_CACHE, OASDIFF_FIXTURE_PAIRS, OASDIFF_FIXTURES, RECORDED_FILES, recordOasdiffFixtures } from "../src/oasdiff-fixtures.ts";

// The recorded outputs of the pinned oasdiff (contract-changes: The contract
// Action; design.md, Technical decisions: T12). For each fixture pair of
// OpenAPI documents, the repository holds what the pinned oasdiff prints with
// the arguments the Action runs it with: `oasdiff breaking` as text and
// `oasdiff changelog --format json`. The pairs make ERR, WARN and INFO
// changes, WARN and INFO changes, INFO changes alone, and none. The recorder
// writes them again with the checksum-verified binary, byte for byte.

let binary: string;
const scratch = mkdtempSync(join(tmpdir(), "tiehall-oasdiff-fixtures-"));

beforeAll(async () => {
  // Downloads and verifies the pinned oasdiff once, when the cache does not hold it yet.
  binary = await cachedOasdiff(OASDIFF_CACHE);
});

afterAll(() => rmSync(scratch, { recursive: true, force: true }));

/** The changes a pair's recorded changelog holds, by level: 3 is ERR, 2 WARN and 1 INFO. */
function levelsOf(pair: string): number[] {
  const changelog = JSON.parse(readFileSync(join(OASDIFF_FIXTURES, pair, "changelog.json"), "utf8")) as { level: number }[];
  return changelog.map(({ level }) => level);
}

describe("the recorded oasdiff outputs", () => {
  it("are regenerated byte for byte by the recorder with the checksum-verified binary", () => {
    const target = join(scratch, "recorded");
    expect(recordOasdiffFixtures(binary, target)).toEqual([...OASDIFF_FIXTURE_PAIRS]);
    for (const pair of OASDIFF_FIXTURE_PAIRS) {
      for (const file of RECORDED_FILES) {
        const committed = join(OASDIFF_FIXTURES, pair, file);
        expect(existsSync(committed), `${pair}/${file} is committed`).toBe(true);
        expect(readFileSync(join(target, pair, file)), `${pair}/${file}`).toEqual(readFileSync(committed));
      }
    }
  });

  it("are of the pinned version, which tools/repo-checks also pins", () => {
    const repoChecks = JSON.parse(readFileSync(new URL("../../../tools/repo-checks/oasdiff.json", import.meta.url), "utf8")) as typeof OASDIFF;
    expect(OASDIFF).toEqual({ version: repoChecks.version, archives: repoChecks.archives });
  });

  it("hold one folder per pair, each with its two documents and its two outputs", () => {
    const folders = readdirSync(OASDIFF_FIXTURES, { withFileTypes: true }).filter((entry) => entry.isDirectory());
    expect(folders.map(({ name }) => name).sort()).toEqual([...OASDIFF_FIXTURE_PAIRS].sort());
    for (const pair of OASDIFF_FIXTURE_PAIRS) {
      expect(readdirSync(join(OASDIFF_FIXTURES, pair)).sort()).toEqual(["base.yaml", "breaking.txt", "changelog.json", "revision.yaml"]);
    }
  });

  it("classify ERR, WARN and INFO changes in the breaking pair", () => {
    const levels = levelsOf("breaking");
    expect(levels.filter((level) => level === 3)).toHaveLength(2);
    expect(levels.filter((level) => level === 2)).toHaveLength(1);
    expect(levels.filter((level) => level === 1).length).toBeGreaterThan(0);
    expect(readFileSync(join(OASDIFF_FIXTURES, "breaking", "breaking.txt"), "utf8")).toMatch(/^3 changes: 2 error, 1 warning, 0 info$/m);
  });

  it("classify WARN and INFO changes and no ERR change in the warning pair", () => {
    const levels = levelsOf("warning");
    expect(levels).toContain(2);
    expect(levels).toContain(1);
    expect(levels).not.toContain(3);
  });

  it("classify INFO changes alone in the informational pair", () => {
    const levels = levelsOf("informational");
    expect(levels.length).toBeGreaterThan(0);
    expect(levels.every((level) => level === 1)).toBe(true);
  });

  it("classify no change in the unchanged pair, whose documents still differ", () => {
    expect(levelsOf("unchanged")).toEqual([]);
    const base = readFileSync(join(OASDIFF_FIXTURES, "unchanged", "base.yaml"), "utf8");
    expect(readFileSync(join(OASDIFF_FIXTURES, "unchanged", "revision.yaml"), "utf8")).not.toBe(base);
  });
});

describe("the checksum-verified binary", () => {
  it("is not extracted or run from an archive whose SHA-256 is not the pinned one", async () => {
    const directory = join(scratch, "tampered");
    const tampered = async () => new Response(new Uint8Array([0x1f, 0x8b, 0x08, 0x00, 1, 2, 3, 4]));
    await expect(installOasdiff({ directory, fetch: tampered, platform: "linux", arch: "x64" })).rejects.toBeInstanceOf(ChecksumError);
    expect(existsSync(join(directory, "oasdiff"))).toBe(false);
  });
});
