import openapiTS, { astToString } from "openapi-typescript";
import type { CommandEntry, CommandField, CommandValue, FieldType } from "./command-table.ts";

// Generating @tiehall/client from the OpenAPI document (public-api: The client
// package `@tiehall/client`; public-api: The license map; design.md, Technical
// decisions: T10; design.md, Self-hosting decisions: S16). Two files are
// generated from openapi/v1.json, the committed document of /api/v1, and
// committed beside the client's own code:
// - src/generated/openapi.ts, the types of every path and operation, written
//   by openapi-typescript, which the client's openapi-fetch calls are typed
//   with;
// - src/generated/commands.ts, the CLI's command table, read from the
//   x-tiehall-cli extension of each operation the CLI offers: each command's
//   name, the operation it runs, the fields it takes as positional arguments,
//   the input it sets itself or by default, and every field the operation
//   takes, with where the call carries it and the JSON types it takes, so the
//   CLI builds its request commands from the document and never imports the
//   command catalog, which is server code under AGPL-3.0.
// The document is read as data. `pnpm client:generate` writes both files, and
// CI's `pnpm check:client` regenerates them and fails when either differs from
// the committed one, so a hand edit, or an API change whose client was not
// regenerated, cannot pass.

/** An OpenAPI 3.1 document, as JSON. */
export type OpenApiDocument = Record<string, unknown>;

/** The generated files, by their path in packages/client. */
export const GENERATED_FILES = ["src/generated/openapi.ts", "src/generated/commands.ts"] as const;

/** An x-tiehall-cli extension the CLI could not build a command from; its message names the operation and the problem. */
export class ClientGenerationError extends Error {
  override name = "ClientGenerationError";
}

const HEADER =
  "// Generated by `pnpm client:generate` from openapi/v1.json, the committed OpenAPI document of /api/v1; do not edit.\n" +
  "// CI regenerates it with `pnpm check:client` and fails when it differs (public-api: The client package `@tiehall/client`).\n";

/** The generated files of the client, by their path in packages/client, from this document. */
export async function generateClient(document: OpenApiDocument): Promise<Record<string, string>> {
  const table = commandTable(document);
  const types = astToString(await openapiTS(structuredClone(document) as never, { alphabetize: true }));
  return {
    "src/generated/openapi.ts": `${HEADER}\n${types}`,
    "src/generated/commands.ts":
      `${HEADER}\n` +
      'import type { CommandEntry } from "../command-table.ts";\n\n' +
      "/** Every command of the CLI that runs an operation, sorted by name, from the x-tiehall-cli extension of each operation it offers. */\n" +
      `export const COMMAND_TABLE: readonly CommandEntry[] = ${JSON.stringify(table, null, 2)};\n`,
  };
}

/**
 * What differs between the generated files and the committed ones, by path in
 * packages/client; undefined when nothing does.
 */
export function clientDrift(generated: Readonly<Record<string, string>>, committed: Readonly<Record<string, string | undefined>>): string | undefined {
  const problems: string[] = [];
  for (const [path, text] of Object.entries(generated)) {
    const was = committed[path];
    if (was === undefined) {
      problems.push(`packages/client/${path} is missing.`);
      continue;
    }
    if (was === text) continue;
    const before = was.split("\n");
    const after = text.split("\n");
    const line = before.findIndex((each, index) => each !== after[index]);
    const at = line === -1 ? before.length : line;
    problems.push(
      [
        `packages/client/${path} differs from what openapi/v1.json generates.`,
        `First difference, at line ${at + 1}:`,
        `  committed: ${before[at]?.trim() ?? "(end of file)"}`,
        `  generated: ${after[at]?.trim() ?? "(end of file)"}`,
      ].join("\n"),
    );
  }
  if (problems.length === 0) return undefined;
  return [...problems, "Run `pnpm client:generate` and commit the files, so the client and the CLI's commands follow the document."].join("\n");
}

const METHODS = ["get", "post", "put", "patch", "delete"] as const;
type Method = (typeof METHODS)[number];

type Json = Record<string, unknown>;

function isObject(value: unknown): value is Json {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Every command of the CLI that the document's operations state in x-tiehall-cli, sorted by name. */
export function commandTable(document: OpenApiDocument): CommandEntry[] {
  const entries: CommandEntry[] = [];
  const owners = new Map<string, string>();
  const paths = isObject(document["paths"]) ? document["paths"] : {};
  for (const [path, item] of Object.entries(paths)) {
    if (!isObject(item)) continue;
    for (const method of METHODS) {
      const operation = item[method];
      if (!isObject(operation) || operation["x-tiehall-cli"] === undefined) continue;
      const where = `${method.toUpperCase()} ${path}`;
      const refuse = (text: string): never => {
        throw new ClientGenerationError(`${where}: ${text}`);
      };
      const cli = operation["x-tiehall-cli"];
      const commands = isObject(cli) ? cli["commands"] : undefined;
      if (!Array.isArray(commands)) refuse("its x-tiehall-cli names no list of commands.");
      for (const command of commands as unknown[]) {
        if (!isObject(command) || typeof command["command"] !== "string" || command["command"] === "") refuse("a command of its x-tiehall-cli has no name.");
        const spec = command as Json & { command: string };
        const other = owners.get(spec.command);
        if (other !== undefined) refuse(`its command ${spec.command} is also a command of ${other}.`);
        owners.set(spec.command, where);
        entries.push(entryOf(document, path, method, operation, spec, refuse));
      }
    }
  }
  return entries.sort((a, b) => (a.command < b.command ? -1 : a.command > b.command ? 1 : 0));
}

function entryOf(document: OpenApiDocument, path: string, method: Method, operation: Json, spec: Json & { command: string }, refuse: (text: string) => never): CommandEntry {
  const positional = stringsOf(spec["arguments"]);
  const input = valuesOf(spec["input"]);
  const defaults = valuesOf(spec["defaults"]);
  const fields = fieldsOf(document, operation, input);
  const names = new Set(fields.map(({ name }) => name));
  for (const name of positional) if (!names.has(name)) refuse(`its command ${spec.command} takes ${name}, which the operation does not take.`);
  for (const name of [...Object.keys(input), ...Object.keys(defaults)]) {
    if (!names.has(name)) refuse(`its command ${spec.command} sets ${name}, which the operation does not take.`);
  }
  const responses = isObject(operation["responses"]) ? operation["responses"] : {};
  return {
    command: spec.command,
    operationId: String(operation["operationId"] ?? ""),
    summary: String(operation["summary"] ?? ""),
    method: method.toUpperCase() as CommandEntry["method"],
    path,
    stability: String(operation["x-stability-level"] ?? ""),
    arguments: positional,
    input,
    defaults,
    fields,
    proposes: Object.hasOwn(responses, "202"),
  };
}

function stringsOf(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((each): each is string => typeof each === "string") : [];
}

function valuesOf(value: unknown): Record<string, CommandValue> {
  if (!isObject(value)) return {};
  return Object.fromEntries(
    Object.entries(value).filter((entry): entry is [string, CommandValue] => ["string", "number", "boolean"].includes(typeof entry[1])),
  );
}

/**
 * Every field an operation takes: its path and query parameters, the fields
 * of its JSON body, and its headers. A body with variants gives the fields of
 * the variants that admit the input the command sets itself, such as a
 * message's kind; a field is required when every one of them requires it.
 */
function fieldsOf(document: OpenApiDocument, operation: Json, input: Readonly<Record<string, CommandValue>>): CommandField[] {
  const parameters = (Array.isArray(operation["parameters"]) ? operation["parameters"] : []).filter(isObject);
  const parameter = (where: "path" | "query" | "header") =>
    parameters
      .filter((each) => each["in"] === where && typeof each["name"] === "string")
      .map((each): CommandField => field(String(each["name"]), where, described(document, each["schema"]), each["required"] === true, each["description"]));
  const body = resolved(document, (((operation["requestBody"] as Json | undefined)?.["content"] as Json | undefined)?.["application/json"] as Json | undefined)?.["schema"]);
  const variants = (isObject(body) && Array.isArray(body["oneOf"] ?? body["anyOf"]) ? ((body["oneOf"] ?? body["anyOf"]) as unknown[]) : body === undefined ? [] : [body])
    .map((variant) => resolved(document, variant))
    .filter(isObject)
    .filter((variant) => Object.entries(input).every(([name, value]) => admits(document, propertiesOf(variant)[name], value)));
  const bodyFields: CommandField[] = [];
  for (const name of [...new Set(variants.flatMap((variant) => Object.keys(propertiesOf(variant))))]) {
    const schemas = variants.map((variant) => propertiesOf(variant)[name]).filter((schema) => schema !== undefined);
    const merged = merge(schemas.map((schema) => described(document, schema)));
    const required = variants.every((variant) => stringsOf(variant["required"]).includes(name));
    const description = schemas.map((schema) => (isObject(schema) ? schema["description"] : undefined)).find((each) => typeof each === "string");
    bodyFields.push(field(name, "body", merged, required, description));
  }
  return [...parameter("path"), ...parameter("query"), ...bodyFields, ...parameter("header")];
}

function field(name: string, where: CommandField["in"], { types, values }: Described, required: boolean, description: unknown): CommandField {
  return {
    name,
    in: where,
    types,
    ...(values === undefined ? {} : { values }),
    required,
    ...(typeof description === "string" && description !== "" ? { description } : {}),
  };
}

function propertiesOf(schema: Json): Json {
  return isObject(schema["properties"]) ? schema["properties"] : {};
}

/** A schema with its $ref, to a component of the document, followed. */
function resolved(document: OpenApiDocument, schema: unknown): unknown {
  let current = schema;
  for (let depth = 0; depth < 10 && isObject(current) && typeof current["$ref"] === "string"; depth += 1) {
    const reference: string = current["$ref"];
    if (!reference.startsWith("#/")) return current;
    current = reference
      .slice(2)
      .split("/")
      .map((part) => part.replaceAll("~1", "/").replaceAll("~0", "~"))
      .reduce<unknown>((node, part) => (isObject(node) ? node[part] : undefined), document);
  }
  return current;
}

interface Described {
  types: FieldType[];
  /** The only values the schema admits; undefined when it admits any of its types. */
  values: (string | number | boolean | null)[] | undefined;
}

const TYPES: readonly FieldType[] = ["string", "integer", "number", "boolean", "object", "array", "null"];

/** The JSON types a schema admits, and its values where it lists them. */
function described(document: OpenApiDocument, schema: unknown): Described {
  const node = resolved(document, schema);
  if (!isObject(node)) return { types: [], values: undefined };
  const alternatives = node["anyOf"] ?? node["oneOf"];
  if (Array.isArray(alternatives)) return merge(alternatives.map((alternative) => described(document, alternative)));
  const types = (Array.isArray(node["type"]) ? node["type"] : [node["type"]]).filter((type): type is FieldType => TYPES.includes(type as FieldType));
  let values: Described["values"];
  if (Object.hasOwn(node, "const")) values = [node["const"] as string];
  else if (Array.isArray(node["enum"])) values = node["enum"] as (string | number | boolean | null)[];
  if (types.length === 0 && values !== undefined) {
    for (const value of values) {
      const type: FieldType = value === null ? "null" : typeof value === "number" ? (Number.isInteger(value) ? "integer" : "number") : (typeof value as FieldType);
      if (!types.includes(type)) types.push(type);
    }
  }
  if (types.length === 0 && (isObject(node["properties"]) || Object.hasOwn(node, "additionalProperties"))) types.push("object");
  return { types, values };
}

/** The types and values of several schemas together: any of them. */
function merge(each: readonly Described[]): Described {
  const types: FieldType[] = [];
  for (const type of each.flatMap((one) => one.types)) if (!types.includes(type)) types.push(type);
  const values = each.every((one) => one.values !== undefined) ? [...new Set(each.flatMap((one) => one.values ?? []))] : undefined;
  return { types, values: each.length === 0 ? undefined : values };
}

/** Whether a property's schema admits a value the command sets; a variant without the property admits nothing for it. */
function admits(document: OpenApiDocument, schema: unknown, value: CommandValue): boolean {
  if (schema === undefined) return false;
  const { values } = described(document, schema);
  return values === undefined || values.includes(value);
}
