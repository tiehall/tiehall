import openapiTS, { astToString } from "openapi-typescript";

// The packet's TypeScript types, generated from the packet JSON Schema
// (handoff-packet: The npm package). @tiehall/packet carries the packet's
// types beside its validator, so the types are written from the committed
// schema, schema/v1-beta.json, into src/types.ts, which is committed, and a
// test fails when the file is not what the schema generates; `pnpm
// packet:generate` writes it after the schema. openapi-typescript writes
// them, from the schema as an OpenAPI 3.1 document's one component, Packet,
// which is how the OpenAPI document of /api/v1 holds the packet too; the file
// then names a packet of either kind.

/** The generated types, relative to this directory. */
export const TYPES_FILE = "src/types.ts";

const HEADER =
  "// Generated by `pnpm packet:generate` from schema/v1-beta.json, the packet JSON Schema; do not edit.\n" +
  "// A test fails when it differs from what the schema generates (handoff-packet: The npm package).\n";

const NAMES =
  "\n/** A handoff packet, tiehall.packet/v1, as the packet JSON Schema defines it. */\n" +
  'export type Packet = components["schemas"]["Packet"];\n' +
  "\n/** A request's packet. */\n" +
  'export type RequestPacket = Extract<Packet, { kind: "request" }>;\n' +
  "\n/** A contract-change request's packet, which carries its contract section. */\n" +
  'export type ContractChangePacket = Extract<Packet, { kind: "contract_change" }>;\n';

/** The text of src/types.ts that the schema's text generates. */
export async function generatedTypes(schemaText: string): Promise<string> {
  const { $schema: _schema, $id: _id, ...schema } = JSON.parse(schemaText) as Record<string, unknown>;
  const document = { openapi: "3.1.0", info: { title: "tiehall.packet/v1", version: "1" }, paths: {}, components: { schemas: { Packet: schema } } };
  const types = astToString(await openapiTS(document as never, { alphabetize: true }));
  return `${HEADER}\n${types}${NAMES}`;
}
